export function isReservedMemberSlug(slug) {
  if (!slug) return false;
  const lower = String(slug).toLowerCase();
  if (BUILTIN_MEMBER_ALIASES.includes(lower)) return false;
  return RESERVED_MEMBER_SLUGS.has(lower);
}
