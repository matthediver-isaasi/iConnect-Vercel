// Generates api/_lib/roleAccessHierarchy.generated.js from the client
// ROLE_ACCESS_MAP so the server-side exclusion check resolves parents from the
// REAL map nesting (several ids are nested under a parent whose id does not
// match their dot-prefix, e.g. page "admin.canvas-links-manager" under module
// "site-builder", "dashboard.view" under module "system").
//
// Run with: npx tsx scripts/generate-role-access-hierarchy.mjs
// A unit test (client/src/lib/roleAccessMap.test.ts) fails if the generated
// file drifts from the client map — re-run this script after editing
// ROLE_ACCESS_MAP.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { ROLE_ACCESS_MAP, LEGACY_TO_NEW_MAPPING, buildRoleAccessHierarchy } from '../client/src/lib/roleAccessMap.ts';

const h = buildRoleAccessHierarchy(ROLE_ACCESS_MAP);

const out = `// AUTO-GENERATED by scripts/generate-role-access-hierarchy.mjs — DO NOT EDIT.
// Derived from client/src/lib/roleAccessMap.ts ROLE_ACCESS_MAP nesting.
// Re-run: npx tsx scripts/generate-role-access-hierarchy.mjs

export const MODULE_IDS = ${JSON.stringify([...h.moduleIds], null, 2)};

export const PAGE_IDS = ${JSON.stringify([...h.pageIds], null, 2)};

export const FEATURE_TO_PAGE = ${JSON.stringify(Object.fromEntries(h.featureToPage), null, 2)};

export const RESOURCE_TO_MODULE = ${JSON.stringify(Object.fromEntries(h.resourceToModule), null, 2)};

// Task #3349: single source of truth for legacy-id aliasing. The server used
// to hand-maintain a copy of this mapping and it drifted (missing entries =
// silently dead exclusions). Now generated from the client mapping.
export const LEGACY_TO_NEW_MAPPING = ${JSON.stringify(LEGACY_TO_NEW_MAPPING, null, 2)};
`;

const dest = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'api', '_lib', 'roleAccessHierarchy.generated.js');
writeFileSync(dest, out);
console.log(`Wrote ${dest}: ${h.moduleIds.size} modules, ${h.pageIds.size} pages, ${h.featureToPage.size} features`);
